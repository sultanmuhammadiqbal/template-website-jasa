import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {validateSite} from "../scripts/validate-site.mjs";
const base=JSON.parse(await readFile(new URL("../config/site.json",import.meta.url),"utf8"));
const imported=structuredClone(base);
imported.brand.name="Bengkel Rapi";
imported.brand.mark="BR";
imported.contact.whatsapp.enabled=false;
imported.contact.email.enabled=false;
validateSite(imported);
assert.equal(imported.brand.name,"Bengkel Rapi");
const invalid=structuredClone(imported);
invalid.theme.accent="#171916";
assert.throws(()=>validateSite(invalid),/WCAG contrast/);
const unsafe=structuredClone(imported);
unsafe.contact.whatsapp.enabled=true;
unsafe.contact.whatsapp.number="";
assert.throws(()=>validateSite(unsafe),/whatsapp.number/);
console.log("Ruang Reka site-config import tests passed: valid brief seed, contrast rejection, invalid contact rejection.");
